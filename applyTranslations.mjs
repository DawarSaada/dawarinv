async function applyTranslations() {
  console.log("Applying professional translations...");
  
  const { data: catItems } = await supabase.from('product_catalog').select('id, name_ar');
  const { data: invItems } = await supabase.from('inventory_items').select('id, name_ar');
  
  let catUpdates = [];
  for (let cat of catItems) {
    let ar = (cat.name_ar || '').trim();
    if (dictionary[ar]) {
      catUpdates.push({ id: cat.id, name_en: dictionary[ar] });
    }
  }
  
  // Bulk update catalog
  for (let u of catUpdates) {
    await supabase.from('product_catalog').update({ name_en: u.name_en }).eq('id', u.id);
  }
  console.log(`Updated ${catUpdates.length} catalog items with professional translations.`);
  
  let invUpdates = [];
  for (let inv of invItems) {
    let ar = (inv.name_ar || '').trim();
    if (dictionary[ar]) {
      invUpdates.push({ id: inv.id, name_en: dictionary[ar] });
    }
  }
  
  // Bulk update inventory
  for (let u of invUpdates) {
    await supabase.from('inventory_items').update({ name_en: u.name_en }).eq('id', u.id);
  }
  console.log(`Updated ${invUpdates.length} inventory items with professional translations.`);
  
  console.log("Translation overhaul complete!");
}

